import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// Ilovaning til (i18n) tizimi.
class AppLocale extends ChangeNotifier {
  AppLocale._internal();
  static final AppLocale instance = AppLocale._internal();

  static const _prefsKey = 'app_language_code';

  String _code = 'uz';
  String get code => _code;

  Future<void> load() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      _code = prefs.getString(_prefsKey) ?? 'uz';
      notifyListeners();
    } catch (_) {}
  }

  Future<void> setLanguage(String code) async {
    if (_code == code) return;
    _code = code;
    notifyListeners();
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefsKey, code);
    } catch (_) {}
  }

  String t(String key) {
    final forLang = _strings[_code] ?? _strings['uz']!;
    return forLang[key] ?? _strings['uz']?[key] ?? key;
  }
}

